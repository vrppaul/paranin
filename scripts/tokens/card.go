package main

import (
	"fmt"
	"strings"
)

// How the cards' file of tokens opens, marked generated, each line a Typst comment
const cardsFileOpening = `// Code generated by scripts/tokens from design/tokens.yaml. DO NOT EDIT.

// The design's tokens as internal/face/card's template draws the cards by them (DESIGN.md, Social cards)

`

// How the cards' face is written, under what it is for; how their colours open and close, under what they are, and
// how a colour is written among them, under what it is for
const (
	cardFace           = "// %s\n#let face = %q\n\n"
	cardColoursOpening = "// The design's colours in the dark theme, Catppuccin Macchiato, the one the cards are drawn in, each #rrggbb: the\n" +
		"// page's own colour, each colour, then each mix, by its token's name\n#let colours = (\n"
	cardColoursClosing = ")\n"
	cardColour         = "  // %s\n  %s: %q,\n"
)

// cardTokens are the cards' tokens as Typst reads them: the page's face, by its first family, which the cards are set
// in; and the page's own colour, each colour and each mix in the dark theme, #rrggbb, each by its token's name, under
// what it is for. A blend stays the stylesheet's until a card lays one.
func cardTokens(read tokens) []byte {
	var builder strings.Builder
	builder.WriteString(cardsFileOpening)
	pageFace := read.page.faces[0]
	fmt.Fprintf(&builder, cardFace, pageFace.about, pageFace.families[0])
	builder.WriteString(cardColoursOpening)
	fmt.Fprintf(&builder, cardColour, read.backgroundAbout, backgroundName, hexColour(read.background.Dark))
	for _, colour := range read.colours {
		fmt.Fprintf(&builder, cardColour, colour.about, colour.name, hexColour(colour.values.Dark))
	}
	for _, mix := range read.page.mixes {
		fmt.Fprintf(&builder, cardColour, mix.about, mix.name, hexColour(mix.values.Dark))
	}
	builder.WriteString(cardColoursClosing)
	return []byte(builder.String())
}
