package main

import (
	"fmt"
	"image/color"
	"strings"
	"unicode"
)

// How the module of the design's colours opens, marked generated: one object of the themes'
const coloursOpening = `// Code generated by scripts/tokens from design/tokens.yaml. DO NOT EDIT.

/**
 * The design's colours in each theme, for a script that draws on a canvas, which reads no custom property: each the
 * stylesheet's own (tokens.css).
 */
export const COLOURS = {
`

// How the module of the design's colours closes: the object of the themes read only, then the type of a theme's name
const coloursClosing = `} as const;

/** A theme the page is shown in, as its root's data-theme names it. */
export type Theme = keyof typeof COLOURS;
`

// The themes as the page's root names them, each an object of the colours' module; how a theme's object opens and
// closes, and how a colour is written in it
const (
	lightScriptTheme = "light"
	darkScriptTheme  = "dark"
	themeOpening     = "  %s: {\n"
	themeClosing     = "  },\n"
	themeColour      = "    /** %s */\n    %s: %q,\n"
)

// How the module of the design's times opens, marked generated: one object of them
const timesOpening = `// Code generated by scripts/tokens from design/tokens.yaml. DO NOT EDIT.

/** The design's times in milliseconds, for a script that waits one: each the stylesheet's own (tokens.css). */
export const TIMES = {
`

// timesScript is the page's module of the tokens' times: each a property, its milliseconds under what it is for. A
// script that waits a time reads it here as a number, not off the stylesheet, which the build writes the shortest
// way, 2400ms as 2.4s.
func timesScript(read tokens) []byte {
	numbers := make([]namedNumber, 0, len(read.page.times))
	for _, timed := range read.page.times {
		numbers = append(numbers, namedNumber{name: timed.name, about: timed.about, number: uint(timed.milliseconds)})
	}
	return scriptNumbers(timesOpening, numbers)
}

// coloursScript is the page's module of the tokens' colours, for a canvas, which reads no custom property: an object
// of each theme's, the page's own colour and then each colour, its value #rrggbb under what it is for. A blend and a
// mix stay the stylesheet's until a script draws one.
func coloursScript(read tokens) []byte {
	var builder strings.Builder
	builder.WriteString(coloursOpening)
	writeThemeColours(&builder, lightScriptTheme, read, func(values themedValue[color.RGBA]) color.RGBA { return values.Light })
	writeThemeColours(&builder, darkScriptTheme, read, func(values themedValue[color.RGBA]) color.RGBA { return values.Dark })
	builder.WriteString(coloursClosing)
	return []byte(builder.String())
}

// writeThemeColours writes a theme's object of colours, each its value in the theme valueIn picks.
func writeThemeColours(builder *strings.Builder, theme string, read tokens, valueIn func(themedValue[color.RGBA]) color.RGBA) {
	fmt.Fprintf(builder, themeOpening, theme)
	fmt.Fprintf(builder, themeColour, read.backgroundAbout, scriptName(backgroundName), hexColour(valueIn(read.background)))
	for _, colour := range read.colours {
		fmt.Fprintf(builder, themeColour, colour.about, scriptName(colour.name), hexColour(valueIn(colour.values)))
	}
	builder.WriteString(themeClosing)
}

// scriptName is the TypeScript name of a token, its words in camel case: slow_blink is slowBlink.
func scriptName(token string) string {
	var builder strings.Builder
	for index, word := range strings.Split(token, wordSeparator) {
		letters := []rune(word)
		if index > 0 && len(letters) > 0 {
			letters[0] = unicode.ToUpper(letters[0])
		}
		builder.WriteString(string(letters))
	}
	return builder.String()
}
