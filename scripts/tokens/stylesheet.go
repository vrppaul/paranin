package main

import (
	"encoding/hex"
	"fmt"
	"image/color"
	"math"
	"strings"
)

// How the generated stylesheet opens: the line that says it is generated, then the rule every colour is a
// property of, whose color-scheme lets the page follow the reader's system until a theme is chosen
const stylesheetOpening = `/* Code generated by scripts/tokens from design/tokens.yaml. DO NOT EDIT. */

/* The design's colours, each named for what it does, its value in the light theme and in the dark one */
:root {
  color-scheme: light dark;
`

// How the stylesheet ends: the rule closed
const stylesheetClosing = "}\n"

// The name of the page's own colour, the token the file writes it under
const backgroundName = "background"

// What a custom property's name is made of: two hyphens, then the token's words, parted by hyphens where the
// file parts them by underscores
const (
	propertyPrefix    = "--"
	propertySeparator = "-"
)

// stylesheet is the CSS of the tokens: a custom property for the page, each colour and each blend, in the order
// the file names them, each its value in both themes. A blend is its colour at its strength, which the browser
// lays over whatever is under it.
func stylesheet(read tokens) []byte {
	var builder strings.Builder
	builder.WriteString(stylesheetOpening)
	writeProperty(&builder, backgroundName, read.backgroundAbout, hexColour(read.background.Light), hexColour(read.background.Dark))
	for _, colour := range read.colours {
		writeProperty(&builder, colour.name, colour.about, hexColour(colour.values.Light), hexColour(colour.values.Dark))
	}
	for _, blend := range read.blends {
		writeProperty(&builder, blend.name, blend.about,
			laidColour(blend.over.Light, blend.strengths.Light), laidColour(blend.over.Dark, blend.strengths.Dark))
	}
	builder.WriteString(stylesheetClosing)
	return []byte(builder.String())
}

// writeProperty writes a custom property under what it is for, its value in each theme.
func writeProperty(builder *strings.Builder, token, about, light, dark string) {
	fmt.Fprintf(builder, "  /* %s */\n  %s: light-dark(%s, %s);\n", about, propertyName(token), light, dark)
}

// propertyName is the CSS name of a token: on_accent is --on-accent.
func propertyName(token string) string {
	return propertyPrefix + strings.ReplaceAll(token, wordSeparator, propertySeparator)
}

// hexColour is a colour as the tokens write it, #rrggbb.
func hexColour(colour color.RGBA) string {
	return colourMark + hex.EncodeToString([]byte{colour.R, colour.G, colour.B})
}

// laidColour is a colour at a strength, as CSS writes one with its opacity after its channels: #rrggbbaa, the
// strength rounded to the nearest of 256 steps.
func laidColour(colour color.RGBA, strength float64) string {
	return colourMark + hex.EncodeToString([]byte{colour.R, colour.G, colour.B, uint8(math.Round(strength * opaque))})
}
