package main

// The key a count is written under, as its tag says
const countKey = "count"

// How the generated Go of the counts opens: the line every linter knows generated code by, then the block of its
// constants
const countsOpening = `// Code generated by scripts/tokens from design/tokens.yaml. DO NOT EDIT.

package look

// The design's counts a terminal lays out by as well as the page, each how many of a thing stand side by side, in the
// order design/tokens.yaml names them
const (
`

// countToken is a count as the file writes it: its name, what it is for, and how many of a thing it is.
type countToken struct {
	Name  string       `yaml:"name"`
	About string       `yaml:"about"`
	Count *wholeNumber `yaml:"count"`
}

// readCount is a count read, a whole number more than none.
type readCount struct {
	name  string
	about string
	count wholeNumber
}

// readCountToken reads a count, more than none of a thing.
func readCountToken(token countToken, named map[string]bool) (readCount, error) {
	if err := checkToken(token.Name, token.About, named); err != nil {
		return readCount{}, err
	}
	count, err := counted(token.Count, token.Name, countKey)
	if err != nil {
		return readCount{}, err
	}
	return readCount{name: token.Name, about: token.About, count: count}, nil
}

// countsSource is the Go of the counts: a constant of its number for each, under what it is for.
func countsSource(read tokens) ([]byte, error) {
	numbers := make([]namedNumber, 0, len(read.page.counts))
	for _, count := range read.page.counts {
		numbers = append(numbers, namedNumber{name: count.name, about: count.about, number: uint(count.count)})
	}
	return goConstants(countsOpening, numbers)
}
