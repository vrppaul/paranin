package main

import (
	"fmt"
	"strings"
	"unicode"
)

// How the module of the design's times opens, marked generated, and closes: one object of them, read only
const (
	scriptOpening = `// Code generated by scripts/tokens from design/tokens.yaml. DO NOT EDIT.

/** The design's times in milliseconds, for a script that waits one: each the stylesheet's own (tokens.css). */
export const TIMES = {
`
	scriptClosing = "} as const;\n"
)

// timesScript is the page's module of the tokens' times: each a property, its milliseconds under what it is for. A
// script that waits a time reads it here as a number, not off the stylesheet, which the build writes the shortest
// way, 2400ms as 2.4s.
func timesScript(read tokens) []byte {
	var builder strings.Builder
	builder.WriteString(scriptOpening)
	for _, timed := range read.page.times {
		fmt.Fprintf(&builder, "  /** %s */\n  %s: %d,\n", timed.about, scriptName(timed.name), timed.milliseconds)
	}
	builder.WriteString(scriptClosing)
	return []byte(builder.String())
}

// scriptName is the TypeScript name of a token, its words in camel case: slow_blink is slowBlink.
func scriptName(token string) string {
	var builder strings.Builder
	for index, word := range strings.Split(token, wordSeparator) {
		letters := []rune(word)
		if index > 0 && len(letters) > 0 {
			letters[0] = unicode.ToUpper(letters[0])
		}
		builder.WriteString(string(letters))
	}
	return builder.String()
}
